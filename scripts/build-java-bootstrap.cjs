#!/usr/bin/env node
"use strict";

// Reproduce the bundled helper from its MIT-licensed Java source. javac is only
// a maintainer dependency; the launcher never downloads a compiler at runtime.
const fs = require("node:fs/promises");
const path = require("node:path");
const os = require("node:os");
const { spawnSync } = require("node:child_process");
const { createHash } = require("node:crypto");

async function main() {
  const root = path.resolve(__dirname, "..");
  const source = path.join(root, "build", "java", "LaunchBootstrap.java");
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), "ldfcl-javac-"));
  try {
    const result = spawnSync(process.argv[2] || "javac", [
      "--release", "8", "-g:none", "-encoding", "UTF-8", "-d", temporary, source,
    ], { encoding: "utf8", windowsHide: true });
    if (result.error) throw result.error;
    if (result.status !== 0) throw Error(result.stderr || "javac failed");
    const compiled = await fs.readFile(path.join(temporary, "io", "ldfcl", "launch", "LaunchBootstrap.class"));
    const sourceHash = createHash("sha256").update(await fs.readFile(source)).digest("hex");
    const classHash = createHash("sha256").update(compiled).digest("hex");
    const output = `// Generated by scripts/build-java-bootstrap.cjs; source: build/java/LaunchBootstrap.java.\n// MIT license; independently implemented for LDFCL. Do not edit the bytecode.\nexport const JAVA_BOOTSTRAP_SOURCE_SHA256 = "${sourceHash}";\nexport const JAVA_BOOTSTRAP_CLASS_SHA256 = "${classHash}";\nexport const JAVA_BOOTSTRAP_CLASS_BASE64 =\n  "${compiled.toString("base64")}";\n`;
    await fs.writeFile(path.join(root, "core", "services", "java-bootstrap-bytecode.ts"), output);
    console.log(`Java 8 bootstrap rebuilt: ${compiled.length} bytes, SHA-256 ${classHash}`);
  } finally {
    await fs.rm(temporary, { recursive: true, force: true });
  }
}
main().catch((error) => { console.error(error.message); process.exitCode = 1; });
